#pragma once
/* Production schema2 journal geometry. Flash offsets, not XIP addresses.
 * Native Default and the old three-slot cache remain outside the journal. */
#include "resident_cache_flash.h"
#include "vial_extension.h"
#include "hardware/flash.h"
#include "compiler_support.h"

#define SM62_LAYOUT_RESERVE_BASE 0x200000u
#define SM62_LAYOUT_RESERVE_END 0x2ca000u
#define SM62_LAYOUT_RESERVED_LOGICAL_RECORDS 100u
#define SM62_LAYOUT_RESERVED_SPARES 1u
#define SM62_LAYOUT_RESERVED_RECORD_SIZE 8192u
#define SM62_LAYOUT_RESERVED_HEADER_BYTES 256u
#define SM62_LAYOUT_RESERVED_COMMIT_BYTES 256u
/* Current maximum complete application FULL: all 16 x 62 keys, visuals,
 * names and encoder stacks; not 100 QMK layers or 100 active cache slots. */
#define SM62_LAYOUT_FULL_PAYLOAD_MAX 4560u
#define SM62_LAYOUT_RESERVE_BYTES (SM62_LAYOUT_RESERVE_END - SM62_LAYOUT_RESERVE_BASE)

STATIC_ASSERT(PICO_FLASH_SIZE_BYTES == 4194304u, "SM62 reservation requires 4 MiB");
STATIC_ASSERT(SM62_CODE_FLASH_LIMIT <= SM62_LAYOUT_RESERVE_BASE, "SM62 code overlaps layout reservation");
STATIC_ASSERT(SM62_LAYOUT_RESERVE_BASE == SM62_CACHE_BASE && SM62_LAYOUT_RESERVE_END == SM62_CACHE_BASE + SM62_CACHE_RECORDS * SM62_CACHE_RECORD_SIZE, "SM62 journal matches reserved geometry");
STATIC_ASSERT(SM62_LAYOUT_RESERVE_BASE < SM62_LAYOUT_RESERVE_END && SM62_LAYOUT_RESERVE_END <= SM62_LEGACY_CACHE_BASE, "SM62 journal must precede legacy cache");
STATIC_ASSERT(SM62_LAYOUT_RESERVE_BASE % FLASH_SECTOR_SIZE == 0 && SM62_LAYOUT_RESERVE_END % FLASH_SECTOR_SIZE == 0, "SM62 reservation erase alignment");
STATIC_ASSERT(SM62_LAYOUT_RESERVED_RECORD_SIZE % FLASH_SECTOR_SIZE == 0, "SM62 reserved record erase alignment");
STATIC_ASSERT(SM62_LAYOUT_RESERVED_HEADER_BYTES == FLASH_PAGE_SIZE && SM62_LAYOUT_RESERVED_COMMIT_BYTES == FLASH_PAGE_SIZE, "SM62 reserved header and commit page alignment");
STATIC_ASSERT(SM62_LAYOUT_RESERVED_LOGICAL_RECORDS == 100 && SM62_LAYOUT_RESERVED_SPARES == 1, "SM62 reserves 100 complete applications plus COW spare");
STATIC_ASSERT(SM62_LAYOUT_RESERVE_BYTES == (SM62_LAYOUT_RESERVED_LOGICAL_RECORDS + SM62_LAYOUT_RESERVED_SPARES) * SM62_LAYOUT_RESERVED_RECORD_SIZE, "SM62 reserved record capacity");
STATIC_ASSERT(SM62_LAYOUT_RESERVED_HEADER_BYTES + SM62_LAYOUT_FULL_PAYLOAD_MAX + SM62_LAYOUT_RESERVED_COMMIT_BYTES <= SM62_LAYOUT_RESERVED_RECORD_SIZE, "SM62 complete FULL must fit reserved record");
STATIC_ASSERT(SM62_LEGACY_CACHE_BASE == 0x3f2000u && SM62_LEGACY_CACHE_END == SM62_EXT_FLASH_BASE && SM62_LEGACY_CACHE_END - SM62_LEGACY_CACHE_BASE == 4 * 8192u, "SM62 legacy cache unchanged");
STATIC_ASSERT(SM62_EXT_FLASH_BASE + 2 * SM62_EXT_BANK_SIZE == 0x3fc000u && 0x3fc000u + 0x4000u == PICO_FLASH_SIZE_BYTES, "SM62 existing extension and EEPROM geometry unchanged");
